def build_french_aliases(output: Path, release: str = "2026.1") -> dict:
    records = []
    seen = set()

    for brand, generic in FRENCH_DRUGS_MAPPING.items():
        alias_norm = normalize(brand)
        canonical_norm = normalize(generic)
        if not alias_norm or not canonical_norm or alias_norm == canonical_norm:
            continue
        key = (alias_norm, canonical_norm)
        if key not in seen:
            seen.add(key)
            records.append({
                "alias": brand.strip(),
                "alias_norm": alias_norm,
                "canonical": generic.strip(),
                "canonical_norm": canonical_norm,
                "kind": "ansm_bdpm",
            })

    for acronym, expanded in FRENCH_ACRONYMS_MAPPING.items():
        alias_norm = normalize(acronym)
        canonical_norm = normalize(expanded)
        if not alias_norm or not canonical_norm or alias_norm == canonical_norm:
            continue
        key = (alias_norm, canonical_norm)
        if key not in seen:
            seen.add(key)
            records.append({
                "alias": acronym.strip().upper(),
                "alias_norm": alias_norm,
                "canonical": expanded.strip(),
                "canonical_norm": canonical_norm,
                "kind": "edn_r2c_acronym",
            })

    for lay_term, medical_term in FRENCH_CLINICAL_SYNONYMS.items():
        alias_norm = normalize(lay_term)
        canonical_norm = normalize(medical_term)
        if not alias_norm or not canonical_norm or alias_norm == canonical_norm:
            continue
        key = (alias_norm, canonical_norm)
        if key not in seen:
            seen.add(key)
            records.append({
                "alias": lay_term.strip(),
                "alias_norm": alias_norm,
                "canonical": medical_term.strip(),
                "canonical_norm": canonical_norm,
                "kind": "french_clinical_synonym",
            })

    records.sort(key=lambda item: (item["alias_norm"], item["canonical_norm"]))

    payload = {
        "format": 1,
        "source": "BDPM / ANSM / EDN / R2C French Medical Vocabulary",
        "release": release,
        "notice": (
            "French medical terminology and drug aliases derived from BDPM, ANSM, "
            "and French medical curriculum (EDN/R2C). Used for local search expansion."
        ),
        "aliases": records,
    }

    encoded = (json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + "\n").encode("utf-8")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(gzip.compress(encoded, compresslevel=9, mtime=0))

    return {
        "aliases": len(records),
        "uncompressed_bytes": len(encoded),
        "compressed_bytes": output.stat().st_size,
    }

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Compile French medical aliases")

SPACE = re.compile(r"\s+")

def normalize(value: str) -> str:
    value = unicodedata.normalize("NFKC", value or "").casefold()
    value = value.replace("’", "'").replace("–", "-").replace("—", "-")
    return SPACE.sub(" ", value).strip()

